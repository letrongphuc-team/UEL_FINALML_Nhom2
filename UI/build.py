"""Regenerate the buildless browser template bundle after editing views/*.html."""
from pathlib import Path
import json
p = Path(__file__).resolve().parent
views = {f.stem: f.read_text(encoding='utf-8') for f in sorted((p/'views').glob('*.html')) if f.stem == 'login'}
shell = (p/'views/shell.html').read_text(encoding='utf-8')
(p/'js/templates.js').write_text('/* Generated by build.py from editable views/*.html */\nwindow.FOLMARE_VIEWS='+json.dumps(views,ensure_ascii=False)+';\nwindow.FOLMARE_SHELL='+json.dumps(shell,ensure_ascii=False)+';\n',encoding='utf-8')
print(f'Built {len(views)} views. No npm dependencies required.')
